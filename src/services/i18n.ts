const STORAGE_KEY = 'takecare_preferred_language';

/**
 * Get current stored language or default to English
 */
export function getSavedLanguage(): SupportedLanguage {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && (saved in TRANSLATIONS)) {
      return saved as SupportedLanguage;
    }
  } catch {
    // localStorage not accessible
  }
  return 'en';
}

/**
 * Save selected language to storage
 */
export function setSavedLanguage(lang: SupportedLanguage): void {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
    // Broadcast event for multi-tab or immediate component updates
    window.dispatchEvent(new CustomEvent('takecare_language_changed', { detail: { language: lang } }));
  } catch {
    // ignore
  }
}

/**
 * Helper to translate a key with fallback to English then to the key itself
 */
export function translate(key: string, lang: SupportedLanguage = getSavedLanguage()): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['en'];
  if (dict && dict[key]) {
    return dict[key];
  }
  // Fallback to English
  if (TRANSLATIONS['en'] && TRANSLATIONS['en'][key]) {
    return TRANSLATIONS['en'][key];
  }
  return key;
}

/**
 * Get human-readable language name for AI prompt instructions
 */
export function getLanguagePromptName(lang: SupportedLanguage): string {
  switch (lang) {
    case 'te': return 'Telugu (తెలుగు)';
    case 'hi': return 'Hindi (हिंदी)';
    case 'ta': return 'Tamil (தமிழ்)';
    case 'mr': return 'Marathi (मराठी)';
    case 'bn': return 'Bengali (বাংলা)';
    case 'kn': return 'Kannada (ಕನ್ನಡ)';
    default: return 'English';
  }
}
